-- ----------------------------------------------------------------------------
-- games — catalogue of playable table games
-- ----------------------------------------------------------------------------
CREATE TABLE games (
  id                    CHAR(36)     NOT NULL,
  slug                  VARCHAR(64)  NOT NULL,
  name                  VARCHAR(128) NOT NULL,
  description           VARCHAR(512) NULL,
  icon_url              VARCHAR(512) NULL,
  min_players           INT          NOT NULL DEFAULT 2,
  max_players           INT          NOT NULL DEFAULT 2,
  avg_duration_minutes  INT          NOT NULL DEFAULT 15,
  supports_bots         TINYINT(1)   NOT NULL DEFAULT 1,
  ranked_enabled        TINYINT(1)   NOT NULL DEFAULT 1,
  status                ENUM('active','inactive','maintenance','coming_soon') NOT NULL DEFAULT 'active',
  created_at            DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at            DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_games_slug (slug),
  KEY idx_games_status (status),
  CONSTRAINT chk_games_players CHECK (min_players >= 1 AND max_players >= min_players)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

