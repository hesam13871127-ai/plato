-- ----------------------------------------------------------------------------
-- reports — user-submitted moderation reports
-- ----------------------------------------------------------------------------
CREATE TABLE reports (
  id              CHAR(36)     NOT NULL,
  reporter_id     CHAR(36)     NOT NULL,
  target_type     ENUM('user','message','room','group') NOT NULL,
  target_id       CHAR(36)     NOT NULL,
  reason          VARCHAR(128) NOT NULL,
  details         TEXT         NULL,
  status          ENUM('open','reviewing','resolved','dismissed') NOT NULL DEFAULT 'open',
  resolved_by     CHAR(36)     NULL,
  resolution_note TEXT         NULL,
  resolved_at     DATETIME(6)  NULL,
  created_at      DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at      DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY idx_reports_reporter (reporter_id),
  KEY idx_reports_target (target_type, target_id),
  KEY idx_reports_status (status),
  CONSTRAINT fk_reports_reporter FOREIGN KEY (reporter_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_reports_resolver FOREIGN KEY (resolved_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- bans — enforcement actions
-- ----------------------------------------------------------------------------
CREATE TABLE bans (
  id          CHAR(36)     NOT NULL,
  user_id     CHAR(36)     NOT NULL,
  type        ENUM('chat','login','matchmaking','permanent') NOT NULL,
  reason      VARCHAR(255) NULL,
  banned_by   CHAR(36)     NULL,
  expires_at  DATETIME(6)  NULL,
  lifted_at   DATETIME(6)  NULL,
  created_at  DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY idx_bans_user (user_id),
  KEY idx_bans_active (user_id, type, expires_at),
  CONSTRAINT fk_bans_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_bans_banner FOREIGN KEY (banned_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- bots — internal AI player configuration (1:1 with bot users)
-- ----------------------------------------------------------------------------
CREATE TABLE bots (
  user_id     CHAR(36)     NOT NULL,
  difficulty  ENUM('easy','medium','hard','expert') NOT NULL DEFAULT 'medium',
  personality VARCHAR(64)  NULL,
  config      JSON         NULL,
  is_active   TINYINT(1)   NOT NULL DEFAULT 1,
  created_at  DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at  DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (user_id),
  KEY idx_bots_difficulty (difficulty),
  KEY idx_bots_active (is_active),
  CONSTRAINT fk_bots_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

