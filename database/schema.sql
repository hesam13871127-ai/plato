-- ----------------------------------------------------------------------------
-- user_inventory — owned items (unique items: 1 row; consumables: quantity)
-- Note: partial unique index is emulated by the application transaction;
--       a generated column keeps unique items one-per-user at the DB level.
-- ----------------------------------------------------------------------------
CREATE TABLE user_inventory (
  id               CHAR(36)     NOT NULL,
  user_id          CHAR(36)     NOT NULL,
  item_id          CHAR(36)     NOT NULL,
  quantity         INT          NOT NULL DEFAULT 1,
  is_equipped      TINYINT(1)   NOT NULL DEFAULT 0,
  is_unique_owned  TINYINT(1)   NOT NULL DEFAULT 1,
  unique_key       CHAR(72)     GENERATED ALWAYS AS
                     (IF(is_unique_owned = 1, CONCAT(user_id, ':', item_id), NULL)) STORED,
  expires_at       DATETIME(6)  NULL,
  acquired_at      DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_inventory_unique_item (unique_key),
  KEY idx_inventory_user (user_id),
  KEY idx_inventory_item (item_id),
  CONSTRAINT fk_inventory_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_inventory_item FOREIGN KEY (item_id) REFERENCES shop_items (id) ON DELETE RESTRICT,
  CONSTRAINT chk_inventory_quantity CHECK (quantity >= 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

