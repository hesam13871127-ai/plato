-- ============================================================================
-- VibeTable — Complete MySQL 8.0+ schema
-- ----------------------------------------------------------------------------
-- This is the canonical production schema. It is executed verbatim by the
-- TypeORM migration `1700000000000-InitialSchema` (see backend/src/database/
-- migrations). All foreign keys, indexes and constraints are defined here;
-- the TypeORM entities mirror this file 1:1 for typed data access.
--
-- Charset: utf8mb4 / utf8mb4_unicode_ci (full emoji + unicode support)
-- Engine:  InnoDB (ACID, foreign-key enforcement)
-- IDs:     CHAR(36) UUIDs (binary-safe, generated by the application layer)
-- Money:   BIGINT unsigned whole coins/gems (no floating point)
-- Time:    DATETIME(6) UTC timestamps with microsecond precision
-- ============================================================================

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- ----------------------------------------------------------------------------
-- users — authentication identities (profiles are 1:1 in `profiles`)
-- ----------------------------------------------------------------------------
CREATE TABLE users (
  id                  CHAR(36)      NOT NULL,
  phone               VARCHAR(20)   NULL,
  phone_normalized    VARCHAR(255)  NULL,
  email               VARCHAR(255)  NULL,
  password_hash       VARCHAR(255)  NULL,
  google_sub          VARCHAR(255)  NULL,
  apple_sub           VARCHAR(255)  NULL,
  primary_provider    ENUM('phone','google','apple','email') NOT NULL DEFAULT 'phone',
  status              ENUM('active','suspended','banned','deleted') NOT NULL DEFAULT 'active',
  is_verified         TINYINT(1)    NOT NULL DEFAULT 0,
  is_bot              TINYINT(1)    NOT NULL DEFAULT 0,  -- INTERNAL: never exposed to clients
  gender              ENUM('male','female','other','unspecified') NOT NULL DEFAULT 'unspecified',
  locale              VARCHAR(32)   NULL,
  date_of_birth       DATE          NULL,
  presence            ENUM('offline','online','in_game','away') NOT NULL DEFAULT 'offline',
  last_seen_at        DATETIME(6)   NULL,
  created_at          DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at          DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  deleted_at          DATETIME(6)   NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_phone (phone),
  UNIQUE KEY uq_users_phone_normalized (phone_normalized),
  UNIQUE KEY uq_users_email (email),
  UNIQUE KEY uq_users_google_sub (google_sub),
  UNIQUE KEY uq_users_apple_sub (apple_sub),
  KEY idx_users_status (status),
  KEY idx_users_is_bot (is_bot),
  KEY idx_users_presence (presence),
  CONSTRAINT chk_users_phone_or_identity CHECK (
    phone IS NOT NULL OR email IS NOT NULL OR google_sub IS NOT NULL OR apple_sub IS NOT NULL
  )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- profiles — public profile, wallet and aggregate stats (1:1 with users)
-- ----------------------------------------------------------------------------
CREATE TABLE profiles (
  user_id         CHAR(36)     NOT NULL,
  username        VARCHAR(32)  NOT NULL,
  display_name    VARCHAR(64)  NOT NULL,
  avatar_url      VARCHAR(512) NULL,
  country         VARCHAR(32)  NULL,
  bio             VARCHAR(512) NULL,
  level           INT          NOT NULL DEFAULT 1,
  xp              INT          NOT NULL DEFAULT 0,
  coins           BIGINT       NOT NULL DEFAULT 0,
  gems            BIGINT       NOT NULL DEFAULT 0,
  games_played    INT          NOT NULL DEFAULT 0,
  games_won       INT          NOT NULL DEFAULT 0,
  games_lost      INT          NOT NULL DEFAULT 0,
  games_drawn     INT          NOT NULL DEFAULT 0,
  streak_days     INT          NOT NULL DEFAULT 0,
  settings        JSON         NULL,
  created_at      DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at      DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (user_id),
  UNIQUE KEY uq_profiles_username (username),
  KEY idx_profiles_level (level),
  KEY idx_profiles_country (country),
  CONSTRAINT fk_profiles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT chk_profiles_wallet CHECK (coins >= 0 AND gems >= 0),
  CONSTRAINT chk_profiles_stats CHECK (
    games_won + games_lost + games_drawn <= games_played
  )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- refresh_tokens — rotating refresh-token families (only hashes stored)
-- ----------------------------------------------------------------------------
CREATE TABLE refresh_tokens (
  id            CHAR(36)     NOT NULL,
  user_id       CHAR(36)     NOT NULL,
  token_hash    CHAR(64)     NOT NULL,
  family_id     CHAR(36)     NOT NULL,
  expires_at    DATETIME(6)  NOT NULL,
  rotated_at    DATETIME(6)  NULL,
  revoked_at    DATETIME(6)  NULL,
  reused        TINYINT(1)   NOT NULL DEFAULT 0,
  ip_address    VARCHAR(45)  NULL,
  user_agent    VARCHAR(512) NULL,
  created_at    DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_refresh_token_hash (token_hash),
  KEY idx_refresh_tokens_user (user_id),
  KEY idx_refresh_tokens_family (family_id),
  KEY idx_refresh_tokens_expires (expires_at),
  CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- otp_codes — SMS one-time passcodes (hashed, short-lived, attempt-bounded)
-- ----------------------------------------------------------------------------
CREATE TABLE otp_codes (
  id            CHAR(36)     NOT NULL,
  phone         VARCHAR(20)  NOT NULL,
  purpose       ENUM('login','verify_phone','reset') NOT NULL DEFAULT 'login',
  code_hash     CHAR(64)     NOT NULL,
  expires_at    DATETIME(6)  NOT NULL,
  attempts      INT          NOT NULL DEFAULT 0,
  max_attempts  INT          NOT NULL DEFAULT 5,
  consumed_at   DATETIME(6)  NULL,
  last_sent_at  DATETIME(6)  NOT NULL,
  created_at    DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY idx_otp_phone (phone),
  KEY idx_otp_expires (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- friendships — directed friend edges (requests, friendships, blocks)
-- ----------------------------------------------------------------------------
CREATE TABLE friendships (
  id             CHAR(36)     NOT NULL,
  requester_id   CHAR(36)     NOT NULL,
  addressee_id   CHAR(36)     NOT NULL,
  status         ENUM('pending','accepted','blocked') NOT NULL DEFAULT 'pending',
  accepted_at    DATETIME(6)  NULL,
  created_at     DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at     DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_friendship_pair (requester_id, addressee_id),
  KEY idx_friendships_requester (requester_id),
  KEY idx_friendships_addressee (addressee_id),
  KEY idx_friendships_status (status),
  CONSTRAINT fk_friendships_requester FOREIGN KEY (requester_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_friendships_addressee FOREIGN KEY (addressee_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT chk_friendships_not_self CHECK (requester_id <> addressee_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

